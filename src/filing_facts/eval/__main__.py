"""Write the evaluation results into the README, or check that they are current.

python -m filing_facts.eval --write     # query the views, rewrite README and docs/eval.md
python -m filing_facts.eval --check     # exit 1 if the README block differs from the views
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from filing_facts.config import Settings
from filing_facts.eval.report import Metrics, current_block, render, splice, strip_date

ROOT = Path(__file__).resolve().parents[3]


def load_metrics(settings: Settings, dataset: str) -> Metrics:
    from google.cloud import bigquery

    client = bigquery.Client(project=settings.gcp_project, location=settings.bq_location)

    def rows(table: str) -> list[dict[str, Any]]:
        sql = f"SELECT * FROM `{settings.gcp_project}.{dataset}.{table}`"  # noqa: S608
        return [dict(r.items()) for r in client.query(sql, location=settings.bq_location).result()]

    return Metrics(by_concept=rows("eval_metrics"), by_size=rows("eval_metrics_by_size"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="filing_facts.eval", description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument(
        "--dataset", default="filing_facts_staging", help="Where the eval views live."
    )
    args = parser.parse_args(argv)

    settings = Settings()
    if not settings.gcp_project:
        raise SystemExit("FF_GCP_PROJECT is required")
    block = render(load_metrics(settings, args.dataset))
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")

    if args.check:
        have = current_block(readme)
        if have is None or strip_date(have) != strip_date(block):
            print("README evaluation block is stale; run: python -m filing_facts.eval --write")
            return 1
        print("README evaluation block is current")
        return 0

    readme_path.write_text(splice(readme, block), encoding="utf-8")
    (ROOT / "docs" / "eval.md").write_text(
        "# Evaluation results\n\nGenerated by `python -m filing_facts.eval --write`; "
        "the same block appears in the README.\n\n" + block + "\n",
        encoding="utf-8",
    )
    print("wrote README.md and docs/eval.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
